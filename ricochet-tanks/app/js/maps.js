// 字元畫 → 格子＋出生點＋傳送門配對（links[i] ＝ 另一端的格子編號，沒有就是 -1）
export function parseMap(def) {
  const grid = new Uint8Array(COLS * ROWS);
  const links = new Int16Array(COLS * ROWS).fill(-1);
  const players = [], enemies = [], ends = {};
  def.rows.forEach((row, y) => {
    for (let x = 0; x < COLS; x++) {
      const ch = row[x] || '.';
      const i = y * COLS + x;
      if (ch === '#') grid[i] = TILE.WALL;
      else if (ch === 'H') grid[i] = TILE.TALL;
      else if (ch === 'x') grid[i] = TILE.CORK;
      else if (ch === 'o') grid[i] = TILE.HOLE;
      else if (ch === '~') grid[i] = TILE.ICE;
      else if (ch === '*') grid[i] = TILE.BUSH;
      else if (ch === 'B') grid[i] = TILE.BARREL;
      else if (PORTAL_CH.includes(ch)) { grid[i] = TILE.PORTAL; (ends[ch] ||= []).push(i); }
      else if (ch >= '1' && ch <= '4') players[+ch - 1] = { x: x + 0.5, y: y + 0.5 };
      else if (ENEMY_LETTER[ch]) enemies.push({ x: x + 0.5, y: y + 0.5, type: ENEMY_LETTER[ch] });
    }
  });
  for (const e of Object.values(ends)) if (e.length === 2) { links[e[0]] = e[1]; links[e[1]] = e[0]; }
  return { grid, links, players: players.filter(Boolean), enemies, name: def.name, id: def.id, chapter: def.chapter };
}

// 格子陣列帶著傳送門配對（炮彈與坦克走一步時要查）；sim 與客人的鏡像都用這個
export function withLinks(grid, links) { grid.links = links; return grid; }
